export function getRecipesFor(species: Species): Recipe[] {
  const profile = species.preparation;
  if (!profile) return [];
  const templates = TEMPLATES[profile] ?? [];
  const name = species.marketName ?? species.commonName;

  return templates.map((template) => {
    const dish = getMediaImage(template.dishKey);
    return {
      id: `${species.slug}-${template.id}`,
      title: template.title.replaceAll("{fish}", name),
      blurb: template.blurb,
      time: template.time,
      difficulty: template.difficulty,
      serves: template.serves,
      ingredients: template.ingredients.map((line) => line.replaceAll("{fish}", name)),
      steps: template.steps.map((line) => line.replaceAll("{fish}", name)),
      image: dish?.image ?? "",
    };
  });
}
